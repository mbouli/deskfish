#!/usr/bin/env python3
"""Turn the PNG art into common/assets_data.c. Run from the project root:

    python3 tools/make_assets.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FISH_DIR = ROOT / "assets" / "fish"
BG_DIR = ROOT / "assets" / "bg_inspo" / "03"
OUT = ROOT / "common" / "assets_data.c"

SCREEN_W = 320
KEY = 0xF81F  # must match GFX_KEY in common/gfx.h

# Alphabetical, matching species_t in common/species.h.
SPECIES = ["Angelfish", "Bass", "Catfish", "Clownfish", "Goldfish", "Pufferfish", "Surgeonfish"]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def pixels(image, keyed):
    out = []
    for r, g, b, a in image.convert("RGBA").getdata():
        if keyed and a < 128:
            out.append(KEY)
            continue
        value = rgb565(r, g, b)
        if value == KEY:
            value = 0xF81E  # a real pixel that happens to equal the key: nudge it
        out.append(value)
    return out


def tiled(layer, width):
    """Repeat a layer sideways to fill `width`."""
    layer = layer.convert("RGBA")
    canvas = Image.new("RGBA", (width, layer.height), (0, 0, 0, 0))
    for x in range(0, width, layer.width):
        canvas.alpha_composite(layer, (x, 0))
    return canvas


def c_array(name, values):
    lines = [f"static const uint16_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "/* Generated by tools/make_assets.py. Do not edit. */",
        '#include "assets.h"',
        "",
    ]

    for name in SPECIES:
        sprite = Image.open(FISH_DIR / f"{name}.png")
        assert sprite.size == (16, 16), f"{name}.png is {sprite.size}, expected 16x16"
        parts.append(c_array(f"fish_{name.lower()}_px", pixels(sprite, keyed=True)))
        parts.append("")

    far = tiled(Image.open(BG_DIR / "far.png"), SCREEN_W)
    sand = tiled(Image.open(BG_DIR / "sand.png"), SCREEN_W)
    back = Image.alpha_composite(far, sand)
    front = Image.open(BG_DIR / "foregound-merged.png").convert("RGBA").crop((0, 0, SCREEN_W, far.height))
    assert back.size == front.size == (SCREEN_W, 192)

    back_px = pixels(back, keyed=False)
    parts.append(c_array("back_px", back_px))
    parts.append("")
    parts.append(c_array("front_px", pixels(front, keyed=True)))
    parts.append("")

    parts.append("const image_t asset_fish[SPECIES_COUNT] = {")
    for name in SPECIES:
        parts.append(f"    [SPECIES_{name.upper()}] = {{16, 16, fish_{name.lower()}_px}},")
    parts.append("};")
    parts.append(f"const image_t asset_back = {{{SCREEN_W}, 192, back_px}};")
    parts.append(f"const image_t asset_front = {{{SCREEN_W}, 192, front_px}};")
    parts.append(f"const uint16_t asset_water = 0x{back_px[0]:04X};")
    parts.append("")

    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
