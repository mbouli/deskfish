#!/usr/bin/env python3
"""Turn the PNG art into common/assets_data.c. Run from the project root:

    python3 tools/make_assets.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FISH_DIR = ROOT / "assets" / "fish"
BG_DIR = ROOT / "assets" / "bg"
OUT = ROOT / "common" / "assets_data.c"

SCREEN_W = 320
SCREEN_H = 240
MASK_CELL = 8  # must match ASSET_MASK_CELL in common/assets.h
KEY = 0xF81F  # must match GFX_KEY in common/gfx.h

# Alphabetical, matching species_t in common/species.h.
SPECIES = ["Angelfish", "Bass", "Catfish", "Clownfish", "Goldfish", "Pufferfish", "Surgeonfish"]


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def pixels(image, keyed):
    out = []
    for r, g, b, a in image.convert("RGBA").getdata():
        if keyed and a < 128:
            out.append(KEY)
            continue
        value = rgb565(r, g, b)
        if value == KEY:
            value = 0xF81E  # a real pixel that happens to equal the key: nudge it
        out.append(value)
    return out


def tiled(layer, width):
    """Repeat a layer sideways to fill `width`."""
    layer = layer.convert("RGBA")
    canvas = Image.new("RGBA", (width, layer.height), (0, 0, 0, 0))
    for x in range(0, width, layer.width):
        canvas.alpha_composite(layer, (x, 0))
    return canvas


def c_array(name, values):
    lines = [f"static const uint16_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 12):
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = [
        "/* Generated by tools/make_assets.py. Do not edit. */",
        '#include "assets.h"',
        "",
    ]

    for name in SPECIES:
        sprite = Image.open(FISH_DIR / f"{name}.png")
        assert sprite.size == (16, 16), f"{name}.png is {sprite.size}, expected 16x16"
        parts.append(c_array(f"fish_{name.lower()}_px", pixels(sprite, keyed=True)))
        parts.append("")

    far = tiled(Image.open(BG_DIR / "far.png"), SCREEN_W).convert("RGB")
    sand = tiled(Image.open(BG_DIR / "sand.png"), SCREEN_W)
    front = Image.open(BG_DIR / "foregound-merged.png").convert("RGBA").crop((0, 0, SCREEN_W, far.height))
    assert far.size == sand.size == front.size == (SCREEN_W, 192)

    # The far layer has two colours: open water, and the distant ruins. Only
    # the ruins' outline is kept; their colour comes from the sky at run time.
    water = far.getpixel((0, 0))
    assert len(far.getcolors()) == 2, "far.png is expected to have exactly two colours"
    parts.append(f"const uint8_t asset_far_mask[192][{SCREEN_W // 8}] = {{")
    for y in range(far.height):
        row = []
        for x0 in range(0, SCREEN_W, 8):
            byte = 0
            for bit in range(8):
                if far.getpixel((x0 + bit, y)) != water:
                    byte |= 1 << bit
            row.append(f"0x{byte:02X}")
        parts.append("    {" + ", ".join(row) + "},")
    parts.append("};")
    parts.append("")

    parts.append(c_array("sand_px", pixels(sand, keyed=True)))
    parts.append("")
    parts.append(c_array("front_px", pixels(front, keyed=True)))
    parts.append("")

    # A coarse map of the screen: 1 where a cell holds any foreground art.
    art_top = SCREEN_H - front.height
    alpha = front.getchannel("A")
    parts.append(f"const uint8_t asset_front_mask[{SCREEN_H // MASK_CELL}][{SCREEN_W // MASK_CELL}] = {{")
    for top in range(0, SCREEN_H, MASK_CELL):
        row = []
        for left in range(0, SCREEN_W, MASK_CELL):
            box = (left, max(top - art_top, 0), left + MASK_CELL, top + MASK_CELL - art_top)
            covered = box[3] > 0 and alpha.crop(box).getextrema()[1] >= 128
            row.append("1" if covered else "0")
        parts.append("    {" + ", ".join(row) + "},")
    parts.append("};")
    parts.append("")

    parts.append("const image_t asset_fish[SPECIES_COUNT] = {")
    for name in SPECIES:
        parts.append(f"    [SPECIES_{name.upper()}] = {{16, 16, fish_{name.lower()}_px}},")
    parts.append("};")
    parts.append(f"const image_t asset_sand = {{{SCREEN_W}, 192, sand_px}};")
    parts.append(f"const image_t asset_front = {{{SCREEN_W}, 192, front_px}};")
    parts.append(f"const uint16_t asset_water = 0x{rgb565(*water):04X};")
    parts.append("")

    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
